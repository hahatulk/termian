test('Build uses the single editable UI source tree, not a second Electron project', () => {
  const html = source('src/ui/index.html').toString('utf8');
  assert.equal(source('dist/web/index.html').toString('utf8'), html);
  assert.ok(html.includes('id="root"'));
  assert.ok(html.includes('assets/ui-process-62a480c2.js'));
  assert.ok(html.includes('assets/reconnectSaga-197a1ef0.css'));
  assert.ok(html.includes('original-bridge.js'));

  const staged = fs.readdirSync(path.join(base, 'dist/web/assets')).sort();
  const input = fs.readdirSync(path.join(base, 'src/ui/assets')).sort();
  assert.equal(input.length, 1358);
  for (const page of ['settings.html', 'background.html']) {
    assert.equal(source('dist/web/' + page).toString('utf8'), source('src/ui/' + page).toString('utf8'));
  }
  assert.deepEqual(staged, input);
  const inventory = JSON.parse(source('src/ui/inventory.json').toString('utf8'));
  const originals = new Map(inventory.map(item => [item.name, item]));
  for (const name of staged) {
    const bytes = source('src/ui/assets/' + name);
    assert.ok(bytes.equals(source('dist/web/assets/' + name)), 'Build did not use editable source: ' + name);
    const record = originals.get(name);
    assert.ok(record, 'Missing asset inventory entry: ' + name);
    if (record.kind === 'static') {
      // Git for Windows (core.autocrlf=true) may check out text SVGs as CRLF.
      // inventory.json records LF byte sizes, so normalize *only* SVG line
      // endings; binary assets and staged source copies remain byte-exact.
      const canonical = name.endsWith('.svg')
        ? Buffer.from(bytes.toString('utf8').replaceAll('\r\n', '\n'))
        : bytes;
      assert.equal(canonical.length, record.originalBytes,
        'Original static asset bytes changed: ' + name);
    }
  }

  const main = source('src/ui/assets/ui-process-62a480c2.js').toString('utf8');
  const react = source('src/ui/assets/reconnectSaga-3b11f62e.js').toString('utf8');
  assert.ok(main.includes('Readable reconstruction'));
  assert.ok(react.includes('Readable reconstruction'));
  assert.ok(react.split('\n').length > 20000, 'Main React bundle should be readable multiline source');
  assert.ok(fs.existsSync(path.join(base, 'src/ui/symbols.json')));
  assert.ok(source('src/local-account.cjs').toString('utf8').includes('SELF_CLOUD_LOCAL_ACCOUNT_RESTORE'));
});

