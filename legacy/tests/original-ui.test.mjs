test('macOS gets a system application menu with Settings and clipboard shortcuts', () => {
  const script = source('src/original-bridge.js').toString('utf8');
  const menu = source('src/bridge/app-menu.js').toString('utf8');
  assert.match(menu, /export async function buildMacApplicationMenu/);
  const macMenu = menu.slice(menu.indexOf('export async function buildMacApplicationMenu'));
  assert.match(macMenu, /item\('Settings…', \(\) => dispatch\(\{type: 'OPEN_SETTINGS'/);
  assert.match(macMenu, /'CmdOrCtrl\+,'/);
  for (const predefined of ['Hide', 'HideOthers', 'ShowAll', 'Services']) {
    assert.ok(macMenu.includes(`item: '${predefined}'`), 'macOS app menu item missing: ' + predefined);
  }
  for (const predefined of ['Copy', 'Paste', 'Cut', 'Undo', 'Redo']) {
    assert.ok(menu.includes(`item: '${predefined}'`), 'Edit menu item missing: ' + predefined);
  }
  // muda rejects an unknown key (e.g. "Plus"), which fails the whole menu
  // and with it the Edit key equivalents Cmd+C/Cmd+V of the WKWebView.
  const keys = new Set(['A', 'Q', '1', '2', ',', '=', '-']);
  for (const [, accelerator] of menu.matchAll(/'((?:CmdOrCtrl|Ctrl)\+[^']*)'/g)) {
    assert.ok(keys.has(accelerator.slice(accelerator.lastIndexOf('+') + 1)), 'Accelerator key muda cannot parse: ' + accelerator);
  }
  assert.match(script, /setAsAppMenu\(\)/);
  assert.match(script, /if \(mac && isPrimary\)/);
});

