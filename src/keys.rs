//! Keychain: in-memory OpenSSH key generation and checks for a typed or
//! imported key: whether it parses, needs a passphrase, and which public
//! key and algorithm it has.

use russh::keys::{decode_secret_key, Algorithm, PrivateKey};
use russh::keys::ssh_key::{private::RsaKeypair, EcdsaCurve, LineEnding};

use crate::vault::key_kind;

#[derive(Clone, Debug, PartialEq)]
pub enum KeyCheck {
    Empty,
    /// Encrypted, and the passphrase is missing or wrong.
    NeedsPassphrase,
    /// Shown as "Incorrect format".
    Invalid,
    Valid { kind: String, public_key: String },
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum KeyAlgorithm {
    Ed25519,
    Ecdsa256,
    Ecdsa384,
    Ecdsa521,
    Rsa(usize),
}

pub struct GeneratedKey {
    pub private_key: String,
    pub public_key: String,
}

/// Generates an OpenSSH key pair in memory. Call on a background worker.
pub fn generate(algorithm: KeyAlgorithm, passphrase: &str) -> Result<GeneratedKey, String> {
    let mut rng = rand10::rng();
    let mut key = match algorithm {
        KeyAlgorithm::Ed25519 => PrivateKey::random(&mut rng, Algorithm::Ed25519),
        KeyAlgorithm::Ecdsa256 => PrivateKey::random(&mut rng, Algorithm::Ecdsa { curve: EcdsaCurve::NistP256 }),
        KeyAlgorithm::Ecdsa384 => PrivateKey::random(&mut rng, Algorithm::Ecdsa { curve: EcdsaCurve::NistP384 }),
        KeyAlgorithm::Ecdsa521 => PrivateKey::random(&mut rng, Algorithm::Ecdsa { curve: EcdsaCurve::NistP521 }),
        KeyAlgorithm::Rsa(bits) => {
            if !(2048..=8192).contains(&bits) {
                return Err("RSA keys must be 2048–8192 bits".into());
            }
            RsaKeypair::random(&mut rng, bits).map(PrivateKey::from)
        }
    }.map_err(|e| e.to_string())?;
    key.set_comment("Generated By Termian");
    let public_key = key.public_key().to_openssh().map_err(|e| e.to_string())?;
    if !passphrase.is_empty() {
        key = key.encrypt(&mut rng, passphrase.as_bytes()).map_err(|e| e.to_string())?;
    }
    let private_key = key.to_openssh(LineEnding::LF).map_err(|e| e.to_string())?.to_string();
    Ok(GeneratedKey { private_key, public_key })
}

/// Decodes an OpenSSH, PEM or PuTTY private key.
pub fn decode(private_key: &str, passphrase: Option<&str>) -> Result<PrivateKey, KeyCheck> {
    if private_key.trim().is_empty() {
        return Err(KeyCheck::Empty);
    }
    let passphrase = passphrase.filter(|p| !p.is_empty());
    match decode_secret_key(private_key, passphrase) {
        Ok(key) => Ok(key),
        Err(_) if is_encrypted(private_key) => Err(KeyCheck::NeedsPassphrase),
        Err(_) => Err(KeyCheck::Invalid),
    }
}

pub fn check(private_key: &str, passphrase: Option<&str>) -> KeyCheck {
    match decode(private_key, passphrase) {
        Ok(key) => {
            let public_key = key.public_key().to_openssh().unwrap_or_default();
            KeyCheck::Valid { kind: key_kind(&public_key), public_key }
        }
        Err(check) => check,
    }
}

/// Whether the key needs a passphrase: the legacy form shows the Passphrase field then.
pub fn is_encrypted(private_key: &str) -> bool {
    if private_key.contains("ENCRYPTED") || private_key.contains("Proc-Type: 4,ENCRYPTED") {
        return true;
    }
    if private_key.trim_start().starts_with("PuTTY-User-Key-File-") {
        return private_key.lines().any(|l| l.starts_with("Encryption:") && !l.ends_with("none"));
    }
    PrivateKey::from_openssh(private_key).is_ok_and(|key| key.is_encrypted())
}

